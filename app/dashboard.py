"""FlightOps KPI dashboard (synthetic data)

Run locally: streamlit run app/dashboard.py
"""
import subprocess
import sys
from pathlib import Path

import pandas as pd
import plotly.express as px
import plotly.graph_objects as go
import streamlit as st

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from flightops.config import settings  # noqa: E402
from flightops.db import run_query   # noqa: E402
from flightops.forecast import forecast_metric, load_daily, plan_resources  # noqa: E402

st.set_page_config(page_title="FlightOps Dashboard", page_icon="✈️", layout="wide")

# ----------- A. Make sure the database exists (the cloud server starts empty) -------------
@st.cache_resource(show_spinner="Building the synthetic database (first start only, ~15 seconds)...")
def ensure_database() -> bool:
    if not settings.db_path.exists() or settings.db_path.stat().st_size < 1_000_000:
        subprocess.run([sys.executable, str(ROOT / "scripts" / "generate_data.py")], check=True)
    return True

ensure_database()    

# ---------- B. Load data with SQL (cached, so pages load fast) ----------
@st.cache_data
def sql(query: str) -> pd.DataFrame:
    r = run_query(query, row_limit=1000)
    return pd.DataFrame(r["rows"], columns=r["columns"])

monthly = sql("""
    SELECT substr(ops_date, 1, 7) AS month,
            ROUND(SUM(labor_hours) / SUM(flights), 2) AS hours_per_flight,
            ROUND(AVG(flights)) AS flights_per_day
    FROM daily_ops GROUP BY month ORDER BY month""")

attrition = sql("""
    WITH months AS (SELECT DISTINCT substr(flight_date, 1, 7) || '-01' AS m FROM flights)
    SELECT substr(m, 1, 7) AS month,
        ROUND(100.0 *
            (SELECt COUNT(*) FROM employees WHERE role = 'Driver'
                AND term_date >=m AND term_date < date(m, '+1 month'))
            / (SELECT COUNT(*) FROM employees WHERE role = 'Driver'
                AND hire_date < m AND (term_date IS NULL OR term_date >= m)), 1) AS attrition_pct
    FROM months ORDER BY m""")

incidents = sql("""
    SELECT substr(incident_date, 1, 4) || '-Q' || ((CAST(substr(incident_date, 6, 2) AS INT) + 2) / 3) AS quarter,
           severity, COUNT(*) AS incidents
    FROM safety_incidents GROUP BY quarter, severity ORDER BY quarter""")

audits = sql("""
    SELECT substr(audit_date, 1, 4) || '-Q' || ((CAST(substr(audit_date, 6, 2) AS INT) + 2) / 3) AS quarter,
           ROUND(100.0 * AVG(passed), 1) AS pass_rate
    FROM safety_audits GROUP BY quarter ORDER BY quarter""")

# ---------- C. Header and KPI cards ----------
st.title("✈️ FlightOps Dashboard")
st.caption("Airline catering operations at an ATL facility: productivity, people, safety and planning.")
st.info("All data is **synthetic** (generated by code). It shows realistic patterns, not real company data.")

before = attrition[attrition.month < "2025-03"].attrition_pct.mean()
after = attrition[attrition.month >= "2025-03"].attrition_pct.mean()
first_hpf, last_hpf = monthly.hours_per_flight.iloc[0], monthly.hours_per_flight.iloc[-1]

c1, c2, c3, c4 = st.columns(4)
c1.metric("Hours per flight (last month)", f"{last_hpf:.2f}",
          f"{(last_hpf / first_hpf - 1) * 100:.1f}% vs first month", delta_color="inverse")
c2.metric("Flights per day (last month)", f"{monthly.flights_per_day.iloc[-1]:,.0f}")
c3.metric("Driver attrition per month", f"{after:.1f}%",
          f"{after - before:.1f} pts vs before incentive", delta_color="inverse")
c4.metric("Safety audit pass rate (last quarter)", f"{audits.pass_rate.iloc[-1]:.1f}%",
          f"{audits.pass_rate.iloc[-1] - 85:+.1f} pts vs 85% target")

# ---------- D. Tabs with charts ----------
tab1, tab2, tab3 = st.tabs(["📉 Productivity", "👷 People & Safety", "🔮 Forecast & Plan"])

with tab1:
    fig = px.line(monthly, x="month", y="hours_per_flight", markers=True,
                  title="Labor hours per flight (lower is better)")
    fig.add_hline(y=16, line_dash="dot", line_color="green", annotation_text="Green target < 16")
    fig.add_hline(y=17, line_dash="dot", line_color="red", annotation_text="Red > 17")
    st.plotly_chart(fig, width="stretch")
    st.plotly_chart(px.bar(monthly, x="month", y="flights_per_day", title="Average flights per day"),
                    width="stretch")

with tab2:
    fig = px.line(attrition, x="month", y="attrition_pct", markers=True,
                  title="Driver monthly attrition (%)")
    fig.add_vline(x="2025-03", line_dash="dash", line_color="gray")
    fig.add_annotation(x="2025-03", y=attrition.attrition_pct.max(), text="+$2/h raise + safety incentive")
    fig.add_hline(y=2, line_dash="dot", line_color="green", annotation_text="Target < 2%")
    st.plotly_chart(fig, width="stretch")
    left, right = st.columns(2)
    left.plotly_chart(px.bar(incidents, x="quarter", y="incidents", color="severity",
                             title="Safety events per quarter"), width="stretch")
    fig = px.line(audits, x="quarter", y="pass_rate", markers=True, title="Safety audit pass rate (%)")
    fig.add_hline(y=85, line_dash="dot", line_color="green", annotation_text="Target 85%")
    right.plotly_chart(fig, width="stretch")

with tab3:
    metric = st.selectbox("Metric to forecast", ["flights", "hours_per_flight", "labor_hours"])
    horizon = st.slider("Days to forecast", 30, 180, 90, step=30)
    f = forecast_metric(metric, horizon_days=horizon)
    hist = load_daily()[metric].iloc[-180:]
    weekly = pd.Series(f["weekly_avg_forecast"])
    fig = go.Figure()
    fig.add_scatter(x=hist.index, y=hist.rolling(7).mean(), name="Actual (7-day avg)")
    fig.add_scatter(x=pd.to_datetime(weekly.index), y=weekly.values, name="Forecast (weekly avg)",
                    line=dict(dash="dash"))
    fig.update_layout(title=f"{metric}: last 180 days and next {horizon} days")
    st.plotly_chart(fig, width="stretch")
    st.caption(f"Model: {f['model']}. Back-test error (MAPE): {f['backtest_mape_pct']}%.")

    st.subheader("Resource plan")
    d1, d2 = st.columns(2)
    start = d1.date_input("Start", pd.Timestamp("2026-11-01"))
    end = d2.date_input("End", pd.Timestamp("2026-11-30"))
    try:
        p = plan_resources(str(start), str(end))
        k1, k2, k3, k4 = st.columns(4)
        k1.metric("Flights / day", f"{p['forecast_flights_daily_avg']:,.0f}")
        k2.metric("Labor hours", f"{p['required_labor_hours_total']:,}")
        k3.metric("FTE needed (+12%)", f"{p['required_fte_incl_12pct_buffer']:,.0f}")
        k4.metric("Trucks (peak day)", p["trucks_needed_peak_day"])
        st.caption(p["assumptions"])
    except ValueError as e:
        st.warning(str(e))

st.divider()
st.caption("Built by Nam Tran · [GitHub](https://github.com/NamTran9694/flightops-copilot)")
